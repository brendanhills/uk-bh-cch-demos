# --- File Generation Logic ---
# This section dynamically creates the .env and terraform.tfvars files
# to ensure consistency across all tools.

echo "🚀 Generating configuration files from config.sh..."

# Generate terraform.tfvars
cat > terraform.tfvars << EOL
# Auto-generated from config.sh
# Do not edit this file directly.

project_id = "${PROJECT_ID}"
region     = "${REGION}"
location   = "${LOCATION}"
EOL
echo "✅ terraform.tfvars generated."

# Generate .env file
cat > .env << EOL
# Auto-generated from config.sh
# Do not edit this file directly.

PROJECT_ID="${PROJECT_ID}"
LOCATION="${LOCATION}"
REGION="${REGION}"
GEMINI_END_USERS_GROUP="${GEMINI_END_USERS_GROUP}"
EOL
echo "✅ .env file generated."


