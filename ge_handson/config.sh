#!/bin/bash

# ==============================================================================
#
# CORE CONFIGURATION & ENVIRONMENT SETUP
#
# ==============================================================================
# This script is the single source of truth for all environment configuration.
# Running this script will:
#   1. Export the variables for your current shell session.
#   2. Generate `terraform.tfvars` for Terraform.
#   3. Generate `.env` for Python scripts.
#
# To run this script, make it executable and run from your shell:
#   chmod +x config.sh
#   ./config.sh
#
# Other scripts can also 'source' this file to inherit its variables.

# --- Master Configuration Values ---
# Define the core project and location settings here.
export PROJECT_ID="ge-hands-on25tst-101"
